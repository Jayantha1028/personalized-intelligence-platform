def seed_sources():
    con = sqlite3.connect("platform.db")
    cur = con.cursor()

    print(f"Upserting {len(SOURCES)} verified sources into platform.db...")

    insert_sql = """
    INSERT INTO sources (
        name, slug, category, source_type, base_url, feed_url, country, region,
        trust_level, enabled, fetch_interval_minutes, last_status, failure_count, created_at
    ) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, 1, ?, 'success', 0, ?)
    """

    for s in SOURCES:
        existing = cur.execute("SELECT id FROM sources WHERE slug = ?", (s["slug"],)).fetchone()
        if existing:
            cur.execute("""
                UPDATE sources SET
                    name = ?, category = ?, source_type = ?, base_url = ?,
                    feed_url = ?, country = ?, region = ?, trust_level = ?,
                    fetch_interval_minutes = ?, last_status = 'success'
                WHERE slug = ?
            """, (
                s["name"], s["category"], s["source_type"], s["base_url"],
                s["feed_url"], s["country"], s["region"], s["trust_level"],
                s["fetch_interval_minutes"], s["slug"]
            ))
        else:
            cur.execute(insert_sql, (
                s["name"], s["slug"], s["category"], s["source_type"], s["base_url"],
                s["feed_url"], s["country"], s["region"], s["trust_level"],
                s["fetch_interval_minutes"], utc_now()
            ))

    con.commit()
    count = cur.execute("SELECT count(*) FROM sources").fetchone()[0]
    print(f"Done! Total verified sources in platform.db: {count}")
    con.close()

